# ✅ What is Pandas? (English)

# Pandas is a popular Python library used for data analysis and data manipulation.

# It helps you work with:

# Tables (rows and columns)
# CSV files
# Excel files
# Large datasets
# Data cleaning and analysis

# Pandas provides two main data structures:

# Series → 1-dimensional data
# DataFrame → 2-dimensional table (like Excel)
